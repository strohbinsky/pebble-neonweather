"""Symbols from tools/symbole.py → src/c/symbole.h (masks for the watch) and src/pkjs/symbole.js (list and preview
on the settings page). Runs in bauen.sh before the build; do not edit either file by hand."""
import json, sys
from pathlib import Path
APP = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(Path(__file__).parent))
import symbole as S

def teile(name):                          # [(mask, dark)] — dark: flat in the edge colour, no 3D edge (moon disc)
    if name in S.MONDE:
        t = ([(S.SCHEIBE, 1)] if name != "VOLL" else []) + ([(S.SYMBOLE[name], 0)] if name != "NEUMOND" else [])
    else:
        assert all(dx == 0 and dy == 0 for _, dx, dy in S.formen(name)), name
        t = [(m, 0) for m, dx, dy in S.formen(name)]
    for m, _ in t:
        assert all(0 <= x < 34 and 0 <= y < 34 for x, y in m), f"{name} sticks out of the cell"
        assert not loch(m), f"{name} has a closed hole — the watch draws symbols without hole handling"
    return t
def loch(m):                              # is there background that cannot be reached from the border?
    aussen, stapel = set(), [(-1, -1)]
    while stapel:
        p = stapel.pop()
        if p in aussen or p in m or not (-1 <= p[0] <= 34 and -1 <= p[1] <= 34): continue
        aussen.add(p); x, y = p; stapel += [(x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)]
    return any((x, y) not in aussen and (x, y) not in m for x in range(34) for y in range(34))
def bytes_von(m):                         # 34 rows of 5 bytes, bit 7 = left column
    out = []
    for y in range(34):
        for b in range(5):
            out.append(sum(0x80 >> i for i in range(8) if (b * 8 + i, y) in m))
    return out
def cname(n): return "SYM_" + n.replace(" ", "_")

alle, start = [], []
for n in S.UHR:
    start.append(len(alle)); alle += teile(n)
start.append(len(alle))
c = ["// Generated by tools/symbole_erzeugen.py from tools/symbole.py — do not edit by hand",
     "// Symbols 34 × 34 px as bitmasks (rows of 5 bytes, bit 7 = left column); symbol s consists of the parts",
     "// SYM_START[s] … SYM_START[s + 1] − 1, each drawn with its own outline; SYM_DUNKEL: flat in the edge colour (moon disc)",
     "#define SYM_GROESSE 34",
     "enum { " + ", ".join(cname(n) for n in S.UHR) + ", SYM_ANZAHL };",
     f"static const uint8_t SYM_TEIL[{len(alle)}][170] = {{"]
for m, _ in alle: c.append("  { " + ", ".join(str(v) for v in bytes_von(m)) + " },")
c += ["};", "static const uint8_t SYM_START[SYM_ANZAHL + 1] = { " + ", ".join(map(str, start)) + " };",
      f"static const uint8_t SYM_DUNKEL[{len(alle)}] = {{ " + ", ".join(str(d) for _, d in alle) + " };", ""]
(APP / "src/c/symbole.h").write_text("\n".join(c))
assert list(S.NAMEN) == S.UHR, "NAMEN in a different order than UHR"
js = {"namen": [S.NAMEN[n] for n in S.UHR],
      "teile": [[[d, "".join("%02X" % v for v in bytes_von(m))] for m, d in teile(n)] for n in S.UHR]}
(APP / "src/pkjs/symbole.js").write_text("// Generated by tools/symbole_erzeugen.py — do not edit by hand. All symbols for the settings page preview,\n"
                                        "// order = enum SYM_… on the watch: parts [dark, 34 rows × 5 bytes as hex, bit 7 = left column]\nmodule.exports = " +
                                        json.dumps(js, separators=(",", ":"), ensure_ascii=False) + ";\n")
print(f"symbols: {len(S.UHR)} symbols, {len(alle)} parts")
