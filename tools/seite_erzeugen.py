"""Settings page src/seite/einstellungen.html → src/pkjs/seite.js (one string, loaded by the phone script via require).
Runs in bauen.sh before the build; do not edit seite.js by hand."""
import json
from pathlib import Path
APP = Path(__file__).resolve().parents[1]
html = (APP / "src/seite/einstellungen.html").read_text()
for p in ("/*ZUSTAND*/null", "/*LISTE*/null", "/*LAGEN*/null", "/*INHALTE*/null", "/*BLOECKE*/null", "/*SYMBOLE*/null"):   # each placeholder exactly once, otherwise the phone script replaces the wrong spot
    assert html.count(p) == 1, f"{p} occurs {html.count(p)} times"
(APP / "src/pkjs/seite.js").write_text("// Generated by tools/seite_erzeugen.py from src/seite/einstellungen.html — do not edit by hand\n"
                                      "module.exports = " + json.dumps(html, ensure_ascii=False) + ";\n")
print("seite.js:", len(html), "characters")
