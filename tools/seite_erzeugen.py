"""Settings page src/seite/einstellungen.html → src/pkjs/seite.js (one string, loaded by the phone script via require).
Since 0.34.0 the page script is packed (deflate) and unpacked in the page by src/seite/entpacken.js.
Runs in bauen.sh before the build; do not edit seite.js by hand.
Since 0.30.0 slimmed down on the way: HTML comments, comment lines and indentation go, the page travels as a data URL."""
import base64, json, re, subprocess, zlib
from pathlib import Path
APP = Path(__file__).resolve().parents[1]
html = (APP / "src/seite/einstellungen.html").read_text()
for p in ("/*ZUSTAND*/null", "/*LISTE*/null", "/*LAGEN*/null", "/*INHALTE*/null", "/*BLOECKE*/null", "/*SYMBOLE*/null", "/*SCHRIFT*/null"):   # each placeholder exactly once, otherwise the phone script replaces the wrong spot
    assert html.count(p) == 1, f"{p} occurs {html.count(p)} times"

def schlank(t):
    t = re.sub(r"<!--.*?-->\n?", "", t, flags=re.S)
    aus = []
    for z in t.split("\n"):
        z = z.strip()
        if not z or z.startswith("//"): continue
        m = re.search(r"\s{2,}// .*$", z)          # comment at the end of a line, only when no string is open in front of it
        if m and z[:m.start()].count('"') % 2 == 0 and z[:m.start()].count("'") % 2 == 0: z = z[:m.start()].rstrip()
        aus.append(z)
    return "\n".join(aus)
klein = schlank(html)
for p in ("/*ZUSTAND*/null", "/*LISTE*/null", "/*LAGEN*/null", "/*INHALTE*/null", "/*BLOECKE*/null", "/*SYMBOLE*/null", "/*SCHRIFT*/null"):
    assert klein.count(p) == 1, f"{p} lost while slimming"

# 0.34.0: packed. The page script goes in compressed (raw deflate, Base64); the static lists are filled in here at build time,
# only the settings (ZUSTAND) come from the phone at runtime, as the global ZS in front of the loader (src/seite/entpacken.js)
daten = json.loads(subprocess.run(["node", "-e", "var l=require('./src/pkjs/logik.js');process.stdout.write(JSON.stringify({L:l.FARBEN,"
                                   "D:l.DRUCKLAGEN,IN:l.INHALTE,BL:l.BLOECKE,SY:require('./src/pkjs/symbole.js'),SC:require('./src/pkjs/schrift.js')}))"],
                                  cwd=APP, capture_output=True, text=True, check=True).stdout)
assert klein.count("<script>") == 1 and klein.count("</script>") == 1, "exactly one script in the page"
a, b = klein.index("<script>") + len("<script>"), klein.index("</script>")
skript = klein[a:b].replace("/*ZUSTAND*/null", "ZS")
for p, k in (("/*LISTE*/null", "L"), ("/*LAGEN*/null", "D"), ("/*INHALTE*/null", "IN"), ("/*BLOECKE*/null", "BL"),
             ("/*SYMBOLE*/null", "SY"), ("/*SCHRIFT*/null", "SC")):
    skript = skript.replace(p, json.dumps(daten[k], ensure_ascii=False, separators=(",", ":")))
z = zlib.compressobj(9, zlib.DEFLATED, -15)
paket = base64.b64encode(z.compress(skript.encode("utf-8")) + z.flush()).decode()
lader = schlank((APP / "src/seite/entpacken.js").read_text())
seite = klein[:a] + "var ZS=/*ZUSTAND*/null;\n" + lader + '\nstarten("' + paket + '");' + klein[b:]
assert seite.count("/*ZUSTAND*/null") == 1
(APP / "src/pkjs/seite.js").write_text("// Generated by tools/seite_erzeugen.py from src/seite/einstellungen.html and entpacken.js — do not edit by hand.\n"
                                      "// Loader page with the packed page script; the phone script fills in /*ZUSTAND*/null\n"
                                      "module.exports = " + json.dumps(seite, ensure_ascii=False) + ";\n")
# 0.35.0: the same page as a configurator for the computer — default look and stock presets filled in, "pc" switches the page to
# "Code for the Pebble". Next to the .pbw: dateien/ in the vault, dist/ in the repo (like tools/bauen.sh)
start = subprocess.run(["node", "-e", "var l=require('./src/pkjs/logik.js');process.stdout.write(JSON.stringify({tag:{farben:l.farbenPruefen(null),"
                        "optionen:l.optionenPruefen(null)},nacht:l.nachtPruefen(null),presets:[],vorlagen:l.kompaktListe(l.vorlagenBasis()),std:l.STD,"
                        "sprache:'en',global:{zeitformat:0},pc:true}).replace(/</g,'\\\\u003c'))"], cwd=APP, capture_output=True, text=True, check=True).stdout
ziel = APP.parent if APP.parent.name == "dateien" else APP / "dist"
ziel.mkdir(exist_ok=True)
(ziel / "neonweather-konfigurator.html").write_text(seite.replace("/*ZUSTAND*/null", start).replace("<title>Neonweather</title>", "<title>Neonweather configurator</title>"))
print("seite.js:", len(html), "→", len(klein), "characters, script", len(skript.encode()), "→", len(paket), "Base64 characters packed")
