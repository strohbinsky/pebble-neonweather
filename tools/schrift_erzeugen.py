"""Letters for the free text (0.28.0), built like the seven-segment digits: one character per digit cell (34 × 34 px), on the
grid of the digit segments — columns 0–8, 8–13, 13–21, 21–26, 26–34 px, rows the same (strokes 8 px, middle at y 13–21).
Strokes lie in the 8 px cells, the 5 px cells only connect. Umlauts use rows 0–6 (dots), 6–10, 10–16, 16–20, 20–26, 26–34.
Digits and the minus are not here: the watch draws them with the clock's ziffer().
Source for src/c/schrift.h (watch) and src/pkjs/schrift.js (character list for the phone, shapes for the page preview).
Runs in bauen.sh before the build; do not edit either output by hand.
Character codes as on the watch: ASCII 32–95 (lower case is sent as upper case), then Ä Ö Ü ° ♥ = 96–100."""
import json
from pathlib import Path
APP = Path(__file__).resolve().parents[1]

G = {   # rows top to bottom, columns left to right; 1 = filled
    "A": "11111 10001 11111 10001 10001", "B": "11110 10001 11111 10001 11110", "C": "11111 10000 10000 10000 11111",
    "D": "11110 10001 10001 10001 11110", "E": "11111 10000 11100 10000 11111", "F": "11111 10000 11100 10000 10000",
    "G": "11111 10000 10011 10001 11111", "H": "10001 10001 11111 10001 10001", "I": "11111 00100 00100 00100 11111",
    "J": "00001 00001 00001 10001 11111", "K": "10001 10011 11110 10011 10001", "L": "10000 10000 10000 10000 11111",
    "M": "10001 11011 10101 10001 10001", "N": "10001 11001 10101 10011 10001", "O": "01110 10001 10001 10001 01110",
    "P": "11111 10001 11111 10000 10000", "Q": "01110 10001 10001 10011 01111", "R": "11111 10001 11111 10010 10001",
    "S": "01111 10000 11111 00001 11110", "T": "11111 00100 00100 00100 00100", "U": "10001 10001 10001 10001 11111",
    "V": "10001 10001 11011 01110 00100", "W": "10001 10001 10101 11011 10001", "X": "10001 11011 01110 11011 10001",
    "Y": "10001 10001 11111 00100 00100", "Z": "11111 00011 01110 11000 11111",
    "Ä": "01010 00000 11111 10001 11111 10001", "Ö": "01010 00000 11111 10001 10001 11111", "Ü": "01010 00000 10001 10001 10001 11111",
    "!": "00100 00100 00100 00000 00100", "?": "11111 00001 00111 00000 00100", ".": "00000 00000 00000 00000 00100",
    ",": "00000 00000 00000 00100 01100", ":": "00000 00100 00000 00100 00000", "'": "00100 00100 00000 00000 00000",
    "+": "00100 00100 11111 00100 00100", "/": "00001 00010 00100 01000 10000", "=": "00000 11111 00000 11111 00000",
    "°": "11100 10100 11100 00000 00000", "♥": "11011 11111 11111 01110 00100", "(": "00011 00100 00100 00100 00011",
    ")": "11000 00100 00100 00100 11000", "%": "11001 11010 00100 01011 10011", "_": "00000 00000 00000 00000 11111",
}
ZIFFERN = "0123456789-"                       # drawn by ziffer() on the watch
ZEICHEN = " " + "".join(G) + ZIFFERN          # everything the phone passes on
SONDER = {"Ä": 96, "Ö": 97, "Ü": 98, "°": 99, "♥": 100}
def code(ch): return SONDER.get(ch, ord(ch))

def maske(zeilen):                            # bit z * 5 + s = row z, column s
    return sum(1 << (z * 5 + s) for z, r in enumerate(zeilen) for s, b in enumerate(r) if b == "1")
def loecher(zeilen):                          # closed holes: empty cells not reachable from outside (4-neighbours), like loecher() for digits
    h, w, aussen, stapel = len(zeilen), 5, set(), [(-1, -1)]
    voll = {(s, z) for z, r in enumerate(zeilen) for s, b in enumerate(r) if b == "1"}
    while stapel:
        p = stapel.pop()
        if p in aussen or p in voll or not (-1 <= p[0] <= w and -1 <= p[1] <= h): continue
        aussen.add(p); s, z = p; stapel += [(s + 1, z), (s - 1, z), (s, z + 1), (s, z - 1)]
    return sum(1 << (z * 5 + s) for z in range(h) for s in range(w) if (s, z) not in voll and (s, z) not in aussen)

tab = [(0, 0, 0)] * 69
for ch, t in G.items():
    zeilen = t.split()
    assert len(zeilen) in (5, 6) and all(len(r) == 5 and set(r) <= {"0", "1"} for r in zeilen), ch
    loch = loecher(zeilen)
    laeufe = sum(1 for z in range(len(zeilen)) for c in range(5) if loch >> (z * 5 + c) & 1 and not (c and loch >> (z * 5 + c - 1) & 1))
    assert laeufe <= 6, f"{ch}: {laeufe} hole pieces, form() takes 6"
    tab[code(ch) - 32] = (maske(zeilen), loch, len(zeilen) - 5)

c = ["// Generated by tools/schrift_erzeugen.py — do not edit by hand",
     "// Letters of the free text (0.28.0) on the grid of the digit segments: m = filled cells, loch = closed holes",
     "// (bit z * 5 + s = row z, column s), art 0 = rows like the digits, 1 = umlaut rows; index = character code − 32, m = 0: no letter",
     "typedef struct { uint32_t m, loch; uint8_t art; } Glyphe;",
     "static const Glyphe SCHRIFT[69] = {"]
for i, (m, l, a) in enumerate(tab):
    ch = next((k for k in G if code(k) == i + 32), "")
    c.append(f"  {{ {m}, {l}, {a} }},{'   // ' + ch if ch else ''}")
c += ["};", ""]
(APP / "src/c/schrift.h").write_text("\n".join(c))
js = {"zeichen": ZEICHEN, "glyphen": {str(code(k)): [maske(t.split()), len(t.split()) - 5] for k, t in G.items()}}
(APP / "src/pkjs/schrift.js").write_text("// Generated by tools/schrift_erzeugen.py — do not edit by hand. Free text (0.28.0): characters the watch can show\n"
                                        "// (zeichen) and the letters for the page preview (glyphen: code → [cells, art], bit z * 5 + s = row z, column s)\n"
                                        "module.exports = " + json.dumps(js, separators=(",", ":"), ensure_ascii=False) + ";\n")
print(f"font: {len(G)} letters and signs, digits from the clock")
